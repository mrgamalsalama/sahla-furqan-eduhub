/**
 * PrimeTimetable schedule matrix rule:
 * Returns whether a subject has a scheduled period on a given day (1..5) for a given shift and grade.
 * If false, it triggers the automatic "No Session" / "لا توجد حصة" populate rule.
 */
export function getTimetableSessionStatus(
  shift: ShiftType,
  grade: string,
  day: number,
  subjectId: string,
  cohort: GenderCohort = 'joint',
  nativeCohort: NativeCohort = 'both',
  teacherName?: string
): { hasSession: boolean; autoNote: string; matchedTeacher?: string } {
  return getTeacherSessionStatus(shift, grade, day, subjectId, cohort, nativeCohort, teacherName);
}

