export function createEmptyDocument(grade: string = 'Grade 11', shift: ShiftType = 'mena'): WeeklyStatementDocument {
  const days: { [day: number]: WeeklySubjectDailyPlan[] } = {};

  for (let d = 1; d <= 5; d++) {
    days[d] = STANDARD_SUBJECTS.map((sub) => {
      const { hasSession, autoNote } = getTimetableSessionStatus(shift, grade, d, sub.id);
      return {
        id: `d${d}-${sub.id}-${Date.now()}`,
        day: d,
        subjectId: sub.id,
        subjectName: sub.nameEn,
        teacherName: '',
        genderCohort: 'joint',
        isNoSession: !hasSession,
        noSessionNote: autoNote,
        contentTopic: !hasSession ? autoNote : '',
        homework: '',
        optionalEnrichment: '',
      };
    });
  }

  return {
    id: `weekly-${grade.toLowerCase().replace(/\s+/g, '-')}-${Date.now()}`,
    grade,
    shift,
    term: '1',
    schoolYear: 'SY 2026-2027',
    weekDateHeader: new Date().toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' }),
    weekRangeText: 'Week of upcoming Sunday',
    days,
    quizzes: [],
    weeklyEducationalValue: '«إِنَّمَا بُعِثْتُ لِأُتَمِّمَ مَكَارِمَ الْأَخْلَاقِ» — فضل العلم والأخلاق الفاضلة',
    updatedAt: Date.now(),
  };
}
