export interface GammaSlide {
  id: string;
  index: number;
  title: string;
  category: string;
  layout: 'hero' | 'split' | 'grid' | 'timeline' | 'quiz' | 'summary' | 'standard';
  contentHtml: string;
  points: string[];
  teacherScript?: string;
  discussionPrompt?: string;
  imageUrl?: string;
  imageCaption?: string;
  fontFamily?: string;
  fontSize?: number;
  isBold?: boolean;
  isItalic?: boolean;
  align?: 'right' | 'center' | 'left' | 'justify';
}

/**
 * Parse raw HTML generated by the AI model into structured Gamma Slide cards
 * and attach matching safe educational images from the curated library.
 */
export function parseHtmlToGammaSlides(
  html: string,
  subject = '',
  topicTitle = ''
): GammaSlide[] {
  if (typeof window === 'undefined' || !html) return [];

  const temp = document.createElement('div');
  temp.innerHTML = html;

  // Check if slides are enclosed in .slide containers
  const slideEls = Array.from(temp.querySelectorAll('.slide'));

  if (slideEls.length > 0) {
    return slideEls.map((el, i) => {
      const titleEl = el.querySelector('h2, h1, h3');
      const title = titleEl?.textContent?.trim() || `شريحة ${i + 1}`;

      // Extract layout attribute or infer
      const layoutAttr = el.getAttribute('data-layout') as GammaSlide['layout'] | null;
      let layout: GammaSlide['layout'] = layoutAttr || (i === 0 ? 'hero' : 'standard');

      // Extract teacher script
      const notesEl = el.querySelector('.teacher-notes, .teacher-script');
      let teacherScript = '';
      let discussionPrompt = '';
      if (notesEl) {
        teacherScript = notesEl.textContent?.trim() || '';
        const match = teacherScript.match(/سؤال[^:]*:\s*(.*)/i);
        if (match && match[1]) {
          discussionPrompt = match[1].trim();
        }
      }

      // Clone el without notes for clean content
      const contentEl = el.cloneNode(true) as HTMLElement;
      contentEl.querySelectorAll('.teacher-notes, .teacher-script, h1, h2, span[style*="border-radius"]').forEach((n) => n.remove());

      // Extract points
      const points: string[] = [];
      contentEl.querySelectorAll('li, p').forEach((p) => {
        const text = p.textContent?.trim();
        if (text && text.length > 4 && !text.includes('الشريحة')) {
          points.push(text);
        }
      });

      // Infer layout if standard
      if (layout === 'standard') {
        const textLower = (title + ' ' + contentEl.textContent).toLowerCase();
        if (textLower.includes('مقارن') || textLower.includes('مقابل') || contentEl.querySelectorAll('table').length > 0) {
          layout = 'split';
        } else if (textLower.includes('أركان') || textLower.includes('محاور') || textLower.includes('عناصر') || points.length >= 3) {
          layout = 'grid';
        } else if (textLower.includes('خطوات') || textLower.includes('مراحل') || textLower.includes('تسلسل')) {
          layout = 'timeline';
        } else if (textLower.includes('سؤال') || textLower.includes('اختبر') || textLower.includes('تحدي')) {
          layout = 'quiz';
        } else if (i === slideEls.length - 1) {
          layout = 'summary';
        }
      }

      // Auto-assign a safe educational image from curated collection
      const rec = getRecommendedImageForSlide(subject || topicTitle, title, i);

      return {
        id: `slide_${i + 1}`,
        index: i + 1,
        title,
        category: i === 0 ? 'الافتتاحية والأهداف' : i === slideEls.length - 1 ? 'الخلاصة والتقويم' : 'المحتوى التفاعلي',
        layout,
        contentHtml: contentEl.innerHTML,
        points: points.length > 0 ? points : [contentEl.textContent?.trim() || ''],
        teacherScript,
        discussionPrompt,
        imageUrl: rec?.url,
        imageCaption: rec?.titleAr,
        fontFamily: 'Cairo',
        align: 'right',
      };
    });
  }

  // Fallback: split by H2 or H1
  const headings = Array.from(temp.querySelectorAll('h1, h2'));
  if (headings.length > 1) {
    return headings.map((h, i) => {
      let content = '';
      let curr = h.nextElementSibling;
      const points: string[] = [];
      let notes = '';

      while (curr && !['H1', 'H2'].includes(curr.tagName)) {
        if (curr.classList.contains('teacher-notes') || curr.textContent?.includes('دليل المعلم')) {
          notes += curr.textContent + ' ';
        } else {
          content += curr.outerHTML;
          if (['P', 'LI'].includes(curr.tagName) && curr.textContent?.trim()) {
            points.push(curr.textContent.trim());
          }
        }
        curr = curr.nextElementSibling;
      }

      const title = h.textContent?.trim() || `شريحة ${i + 1}`;
      const rec = getRecommendedImageForSlide(subject || topicTitle, title, i);

      return {
        id: `slide_${i + 1}`,
        index: i + 1,
        title,
        category: i === 0 ? 'الافتتاحية' : 'المحتوى',
        layout: i === 0 ? 'hero' : 'standard',
        contentHtml: content,
        points: points.length > 0 ? points : [content],
        teacherScript: notes.trim(),
        imageUrl: rec?.url,
        imageCaption: rec?.titleAr,
        fontFamily: 'Cairo',
        align: 'right',
      };
    });
  }

  // Single card fallback
  const rec = getRecommendedImageForSlide(subject || topicTitle, 'عرض عام', 0);
  return [
    {
      id: 'slide_1',
      index: 1,
      title: 'عرض تقديمي تعليمي',
      category: 'عام',
      layout: 'hero',
      contentHtml: html,
      points: [temp.textContent?.trim() || ''],
      imageUrl: rec?.url,
      imageCaption: rec?.titleAr,
      fontFamily: 'Cairo',
      align: 'right',
    },
  ];
}

/**
 * Safely fetches an image and converts to a Base64 data URL.
 * If CORS, network, or timeout occurs, gracefully returns null instead of throwing.
 */
async function fetchImageAsBase64Safe(url?: string): Promise<string | null> {
  if (!url || typeof window === 'undefined') return null;
  if (url.startsWith('data:image/')) return url;

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 3500);
    const res = await fetch(url, { signal: controller.signal, mode: 'cors' });
    clearTimeout(timeout);
    if (!res.ok) return null;
    const blob = await res.blob();
    return new Promise((resolve) => {
      const reader = new FileReader();
      reader.onloadend = () => {
        resolve(typeof reader.result === 'string' ? reader.result : null);
      };
      reader.onerror = () => resolve(null);
      reader.readAsDataURL(blob);
    });
  } catch (err) {
    console.warn('Image fetch failed (CORS or network), continuing without image:', err);
    return null;
  }
}

/**
 * Export Gamma Slides directly to genuine Microsoft PowerPoint (.pptx) file
 * with embedded real educational images, custom formatting, and teacher notes.
 */
export async function exportGammaSlidesToPptx(
  slides: GammaSlide[],
  themeId: GammaThemeId = 'navy',
  title = 'عرض تقديمي تفاعلي',
  schoolName = 'أكاديمية سهلة & مدارس الفرقان'
): Promise<void> {
  if (!slides || slides.length === 0) {
    throw new Error('لا توجد شرائح لتصديرها');
  }

  const theme = GAMMA_THEMES[themeId] || GAMMA_THEMES.navy;
  const pptx = new pptxgen();

  pptx.layout = 'LAYOUT_16x9';
  pptx.rtlMode = true;
  pptx.author = 'منصة سهلة والفرقان الذكية';
  pptx.company = schoolName;
  pptx.title = title;

  // Pre-load all slide images into safe Base64 strings in parallel to avoid CORS failures in pptxgenjs
  const imageBase64List = await Promise.all(
    slides.map((s) => (s.imageUrl ? fetchImageAsBase64Safe(s.imageUrl) : Promise.resolve(null)))
  );

  slides.forEach((slide, idx) => {
    const s = pptx.addSlide();
    const fontFace = slide.fontFamily || 'Cairo';
    const isRtl = slide.align !== 'left';
    const base64Img = imageBase64List[idx];

    // 1. HERO COVER SLIDE
    if (slide.layout === 'hero') {
      s.background = { color: theme.bgHex };

      // Left Image / Visual Card (if present and safely loaded)
      if (base64Img) {
        try {
          s.addImage({
            data: base64Img,
            x: '6%',
            y: '18%',
            w: '38%',
            h: '68%',
            rounding: true,
          });
        } catch {
          // Gracefully continue
        }
      }

      const textWidth = base64Img ? '46%' : '84%';
      const textX = base64Img ? '48%' : '8%';

      // Top school badge
      s.addText(schoolName, {
        x: textX,
        y: '16%',
        w: textWidth,
        h: '8%',
        fontSize: 14,
        color: theme.accentHex,
        bold: true,
        align: 'right',
        fontFace,
        rtl: true,
      } as any);

      // Main Title
      s.addText(slide.title, {
        x: textX,
        y: '26%',
        w: textWidth,
        h: '28%',
        fontSize: 30,
        bold: true,
        color: theme.isDark ? 'FFFFFF' : theme.textHex,
        align: 'right',
        fontFace,
        rtl: true,
      } as any);

      // Bullets / Learning Goals
      if (slide.points.length > 0) {
        const bulletsText = slide.points.slice(0, 4).map((p) => ({
          text: `•  ${p}\n`,
          options: {
            fontSize: 15,
            color: theme.isDark ? 'E2E8F0' : theme.subtextHex,
            fontFace,
            rtl: true,
          } as any,
        }));

        s.addText(bulletsText as any, {
          x: textX,
          y: '56%',
          w: textWidth,
          h: '32%',
          align: 'right',
          valign: 'top',
        });
      }
    } else {
      // 2. CONTENT / INTERACTIVE SLIDES
      s.background = { color: theme.isDark ? theme.bgHex : 'FFFFFF' };

      // Top Header Title
      s.addText(slide.title, {
        x: '6%',
        y: '6%',
        w: '75%',
        h: '12%',
        fontSize: 22,
        bold: true,
        color: theme.isDark ? 'FFFFFF' : theme.textHex,
        align: slide.align || 'right',
        fontFace,
        rtl: isRtl,
      } as any);

      // Slide index badge
      s.addText(`شريحة ${slide.index} من ${slides.length}`, {
        x: '83%',
        y: '7%',
        w: '12%',
        h: '8%',
        fontSize: 11,
        bold: true,
        color: theme.accentHex,
        align: 'center',
        fontFace,
      });

      // Decorative divider
      s.addShape(pptx.ShapeType.rect, {
        x: '6%',
        y: '18%',
        w: '88%',
        h: '0.04%',
        fill: { color: theme.accentHex },
      });

      // Content with or without Image
      const hasImg = Boolean(base64Img);
      const textW = hasImg ? '50%' : '84%';
      const textX = hasImg ? '44%' : '8%';

      // Embed Image on Left
      if (base64Img) {
        try {
          s.addImage({
            data: base64Img,
            x: '6%',
            y: '22%',
            w: '34%',
            h: '64%',
            rounding: true,
          });

          if (slide.imageCaption) {
            s.addText(slide.imageCaption, {
              x: '6%',
              y: '87%',
              w: '34%',
              h: '6%',
              fontSize: 10,
              color: '94A3B8',
              align: 'center',
              fontFace,
              italic: true,
            });
          }
        } catch {
          // Gracefully continue
        }
      }

      // Add Text Points
      if (slide.points.length > 0) {
        const textObjects = slide.points.map((pt) => ({
          text: `•  ${pt}\n`,
          options: {
            fontSize: slide.fontSize || 15,
            color: theme.isDark ? 'E2E8F0' : theme.textHex,
            fontFace,
            bold: slide.isBold || false,
            italic: slide.isItalic || false,
            lineSpacingMultiple: 1.3,
            rtl: isRtl,
          },
        }));

        s.addText(textObjects, {
          x: textX,
          y: '22%',
          w: textW,
          h: '66%',
          align: slide.align || 'right',
          valign: 'top',
        });
      }
    }

    // Attach Teacher Script as genuine PowerPoint Speaker Notes
    if (slide.teacherScript) {
      s.addNotes(slide.teacherScript);
    }
  });

  const safeTitle = (title || 'عرض_تقديمي_Gamma')
    .trim()
    .replace(/[\/\\:*?"<>|]/g, '_')
    .slice(0, 80);
  const safeFileName = `${safeTitle}.pptx`;

  try {
    const output = await pptx.write({ outputType: 'blob' });
    const blob =
      output instanceof Blob
        ? output
        : new Blob([output as any], {
            type: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
          });

    saveAs(blob, safeFileName);
  } catch (blobErr) {
    console.warn('saveAs blob write failed, falling back to pptx.writeFile:', blobErr);
    await pptx.writeFile({ fileName: safeFileName });
  }
}
